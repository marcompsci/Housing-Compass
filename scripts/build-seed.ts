/**
 * Generates supabase/seed/seed.sql from the validated core data.
 *   npx tsx scripts/build-seed.ts
 *
 * Production seed = sources + research leads as SOURCE_LISTED_UNVERIFIED.
 * Demo fixtures are written to a SEPARATE file (seed.demo.sql) for local/dev only.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ADAPTERS, PROGRAMS, demoListings, insertSql, laResearchLeads, listingToRows, researchLeads, type Listing } from "../packages/core/src/index";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

function sourcesSql(): string {
  const rows = [...ADAPTERS, { id: "demo", name: "Demo fixtures (fictional)", kind: "demo_fixture", homeUrl: "https://example.invalid/", termsUrl: null, capabilities: { ingest: true, linkOut: false }, legalBasis: "Fictional records for development.", ingestBlockedBy: null }];
  return rows
    .map(
      (a) =>
        `insert into sources (id, name, kind, home_url, terms_url, can_ingest, can_link_out, legal_basis, ingest_blocked_by) values (${q(a.id)}, ${q(a.name)}, ${q(a.kind)}, ${q(a.homeUrl)}, ${q(a.termsUrl)}, ${q(a.capabilities.ingest)}, ${q(a.capabilities.linkOut)}, ${q(a.legalBasis)}, ${q(a.ingestBlockedBy)}) on conflict (id) do update set legal_basis = excluded.legal_basis, can_ingest = excluded.can_ingest, ingest_blocked_by = excluded.ingest_blocked_by;`,
    )
    .join("\n");
}

function listingSql(l: Listing): string {
  const { listing, unit } = listingToRows(l);
  // units has a surrogate uuid key, so guard with NOT EXISTS for idempotent re-runs.
  const unitInsert = insertSql("units", unit, "do nothing").replace(/ on conflict do nothing;$/, ";");
  const guarded = unitInsert.replace(/^insert into units \(([^)]*)\) values \((.*)\);$/s, `insert into units ($1) select $2 where not exists (select 1 from units where listing_id = ${q(l.id)});`);
  return `${insertSql("listings", listing, "(id) do nothing")}\n${guarded}`;
}

const arr = (xs: string[]) => `array[${xs.map(q).join(", ")}]::text[]`;
function programsSql(): string {
  return PROGRAMS.map(
    (p) =>
      `insert into programs (id, regions, name, operator, kind, url, phone, tty, hours, what_it_is, waitlist_info, eligibility_info, vacancy_info, checked_on, sources) values (${q(p.id)}, ${arr(p.regions)}, ${q(p.name)}, ${q(p.operator)}, ${q(p.kind)}, ${q(p.url)}, ${q(p.phone)}, ${q(p.tty)}, ${q(p.hours)}, ${q(p.whatItIs)}, ${q(p.waitlistInfo)}, ${q(p.eligibilityInfo)}, ${q(p.vacancyInfo)}, ${q(p.checkedOn)}, ${arr(p.sources)}) on conflict (id) do nothing;`,
  ).join("\n");
}

const header = (title: string) => `-- ${title}\n-- GENERATED by scripts/build-seed.ts — do not edit by hand.\n-- Generated at ${new Date().toISOString()}\n\nbegin;\ndo $$ begin perform set_config('app.reason', 'seed import', true); end $$;\n`;

mkdirSync(join(root, "supabase/seed"), { recursive: true });

const leads = [...researchLeads(), ...laResearchLeads()];
if (leads.some((l) => l.verification.level !== "SOURCE_LISTED_UNVERIFIED")) throw new Error("Research leads must be unverified");
writeFileSync(
  join(root, "supabase/seed/seed.sql"),
  `${header("Production-safe seed: data sources + research leads (UNVERIFIED ONLY)")}\n${sourcesSql()}\n\n-- Official programs (reviewed edits go through program_edits afterwards)\n${programsSql()}\n\n${leads.map(listingSql).join("\n\n")}\n\ncommit;\n`,
);

const demo = demoListings(new Date());
writeFileSync(
  join(root, "supabase/seed/seed.demo.sql"),
  `${header("DEV ONLY: fictional demo listings. Never load in production.")}\n${demo.map(listingSql).join("\n\n")}\n\ncommit;\n`,
);
console.log(`seed.sql: ${leads.length} unverified leads (Bay Area + LA); seed.demo.sql: ${demo.length} fictional demo listings`);
